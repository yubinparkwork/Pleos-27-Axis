import {execFileSync} from 'node:child_process';
import {readFile,writeFile,mkdir,cp} from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const args=process.argv.slice(2);
const lookIndex=args.indexOf('--look');
const look=lookIndex<0?null:args.splice(lookIndex,2)[1];
if(lookIndex>=0 && !['cube0914','hybrid-ab'].includes(look))throw Error('Supported look: cube0914, hybrid-ab');
const fromIndex=args.indexOf('--from');
const from=fromIndex<0?null:args.splice(fromIndex,2)[1];
const buildIndex=args.indexOf('--from-build');
const fromBuild=buildIndex<0?null:args.splice(buildIndex,2)[1];
const sequenceIndex=args.indexOf('--sequence');
const sequence=sequenceIndex<0?null:args.splice(sequenceIndex,2)[1];
const transitionIndex=args.indexOf('--transition');
const transition=transitionIndex<0?null:args.splice(transitionIndex,2)[1];
if(from && fromBuild)throw Error('Choose --from or --from-build, not both');
if(buildIndex>=0 && !fromBuild)throw Error('--from-build requires a directory');
if(sequenceIndex>=0 && sequence!=='pleos25')throw Error('Supported sequence: pleos25');
if(transitionIndex>=0 && (transition!=='layered'||sequence!=='pleos25'))throw Error('--transition layered requires --sequence pleos25');
if(from && !/^[a-z0-9-]+$/.test(from))throw Error('Invalid source checkpoint');
const name=args.join(' ').trim();
if(!name)throw Error('Usage: node scripts/save-site-version.mjs "버전 이름"');
if(!from && !fromBuild)execFileSync('npm',['run','build','--','--base','./'],{cwd:root,stdio:'inherit'});
const id='saved-'+new Date().toISOString().replace(/[^0-9]/g,'');
const dest=path.join(root,'public/versions',id);await mkdir(dest,{recursive:true});
const sourceRoot=from?path.join(root,'public/versions',from):fromBuild?path.resolve(fromBuild):path.join(root,'dist');
await cp(sourceRoot,dest,{recursive:true,filter:source=>!path.relative(sourceRoot,source).split(path.sep).includes('versions')});
let html=await readFile(path.join(dest,'index.html'),'utf8');
html=html.replaceAll('/Pleos-27-Axis/assets/','./assets/').replace(/<script[^>]*src="[^"]*version-menu\.js"[^>]*><\/script>/g,'');
const isolation=`<script>(()=>{const p=${JSON.stringify(id+':')};const s=localStorage;Object.defineProperty(window,'localStorage',{value:{getItem:k=>s.getItem(p+k),setItem:(k,v)=>s.setItem(p+k,v),removeItem:k=>s.removeItem(p+k)}})})()</script>`;
if(from)html=html.replaceAll(from+':',id+':');
else html=html.replace('<head>','<head>'+isolation);
html=html.replace('</body>','<script src="../../version-menu.js" defer></script></body>');
await writeFile(path.join(dest,'index.html'),html);
const file=path.join(root,'versions.json');const versions=JSON.parse(await readFile(file,'utf8'));
versions.unshift({id,label:new Date().toLocaleDateString('ko-KR',{timeZone:'Asia/Seoul'})+' · '+name,note:'로컬 실행본 보관 · 브라우저 개인 설정은 별도 저장',localBuild:true,...(from?{sourceId:from}:{}),...(sequence?{sequence}:{}),...(transition?{transition}:{}),...(look?{look}:{})});
await writeFile(file,JSON.stringify(versions,null,2)+'\n');
execFileSync(process.execPath,['scripts/build-version-archive.mjs'],{cwd:root,stdio:'inherit'});
console.log('Saved local site version:',id);
